"""reference.py — loads the original compose() from anim/scripts/anim.py.

anim.py is a generator script: it rebuilds every asset from bg.py and only then
defines compose(). We run it unmodified in a temporary folder (so it cannot
overwrite the shipped art), stopping just before it starts writing the preview
GIFs. The only edit is the hard-coded os.chdir('/tmp/cabin') line, which is
pointed at the temporary folder instead.

Exports:
    load_reference() -> namespace dict with compose, TIMES, SPOTS, ...
    check_regenerated_assets(ns) -> list of (file, differing_pixels)
"""
import os, shutil, sys, tempfile
from pathlib import Path
import numpy as np
from PIL import Image

ANIM = Path(__file__).resolve().parent.parent / 'anim'
STOP_AT = "for t in TIMES: gif('preview_'"   # first line that writes previews
# Sheets anim.py makes that a later script redraws; they are expected to differ.
REDRAWN_LATER = {f'waterfall_{t}.png': 'scripts/waterfall.py' for t in ('morning', 'day', 'afternoon', 'night')}


def shipped(name):
    """Where a file anim.py writes (flat) now lives in the organised anim/ folder."""
    hits = [p for p in ANIM.rglob(name) if 'previews' not in p.parts]
    assert len(hits) == 1, f'{name}: found {hits}'
    return hits[0]


def load_reference():
    work = Path(tempfile.mkdtemp(prefix='cabin_ref_'))
    for f in ('anim.py', 'bg.py', 'make.py', 'wind.py'):
        shutil.copy(ANIM / 'scripts' / f, work / f)
    # Inputs anim.py reads from its working folder (the original hand-made art).
    for f in ('cabin_window.png', 'wind_gust.png', 'wind_streak.png'):
        shutil.copy(shipped(f), work / f)
    src = (work / 'anim.py').read_text()
    src = src.replace("os.chdir('/tmp/cabin')", 'os.chdir(%r)' % str(work))
    src = src[:src.index(STOP_AT)]
    ns = {'__name__': 'anim_reference'}
    cwd = os.getcwd()
    try:
        exec(compile(src, 'anim.py', 'exec'), ns)
    finally:
        os.chdir(cwd)
    ns['WORK'] = work
    return ns


def check_regenerated_assets(ns):
    """Compare every PNG anim.py regenerated against the shipped copy."""
    out = []
    for f in sorted((ns['WORK'] / 'anim').glob('*.png')):
        a = np.asarray(Image.open(f).convert('RGBA'), dtype=np.int16)
        b = np.asarray(Image.open(shipped(f.name)).convert('RGBA'), dtype=np.int16)
        diff = -1 if a.shape != b.shape else int(np.any(a != b, axis=2).sum())
        out.append((f.name, diff))
    for t in ns['TIMES']:   # backgrounds are regenerated by bg.py into the work folder root
        a = np.asarray(ns['BG'][t], dtype=np.int16)
        b = np.asarray(Image.open(shipped(f'bg_{t}.png')).convert('RGBA'), dtype=np.int16)
        out.append((f'bg_{t}.png', int(np.any(a != b, axis=2).sum())))
    return out


if __name__ == '__main__':
    ns = load_reference()
    results = check_regenerated_assets(ns)
    later = [r for r in results if r[0] in REDRAWN_LATER]
    bad = [r for r in results if r[1] != 0 and r[0] not in REDRAWN_LATER]
    print(f'{len(results) - len(later)} assets regenerated, {len(bad)} differ from the shipped files')
    for name, d in bad:
        print('  ', name, d)
    print(f'{len(later)} redrawn later and not compared: ' + ', '.join(f'{n} ({REDRAWN_LATER[n]})' for n, _ in later))
    sys.exit(1 if bad else 0)
